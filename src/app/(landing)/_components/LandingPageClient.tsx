function ProgramTabs({
  tabs, activeTab, setActiveTab,
}: {
  tabs: string[]
  activeTab: string
  setActiveTab: (t: string) => void
}) {
  const btnRefs = useRef<(HTMLButtonElement | null)[]>([])
  const [pill, setPill] = useState({ left: 0, width: 0 })
  const [ready, setReady] = useState(false)

  useEffect(() => {
    const idx = tabs.findIndex(t => t === activeTab)
    const el = btnRefs.current[idx === -1 ? 0 : idx]
    if (el) {
      setPill({ left: el.offsetLeft, width: el.offsetWidth })
      setReady(true)
    }
  }, [activeTab, tabs])

  const [isOpen, setIsOpen] = useState(false)

  return (
    <>
      {/* DESKTOP TABS */}
      <div className="hidden md:flex justify-center w-full mb-12 md:mb-16">
        <div className="relative inline-flex items-center bg-[#063D2A] p-1.5 rounded-full shadow-xl border border-[#042C1E]">
          {ready && (
            <motion.div
              animate={{ left: pill.left, width: pill.width }}
              transition={{ type: 'spring', bounce: 0.15, duration: 0.35 }}
              className="absolute top-1.5 bottom-1.5 bg-[#FCE138] rounded-full shadow-md z-0 pointer-events-none"
            />
          )}
          {tabs.map((tab, i) => (
            <button
              key={tab}
              ref={el => { btnRefs.current[i] = el }}
              onClick={() => setActiveTab(tab)}
              className={`relative z-10 px-7 py-3 rounded-full text-xs font-black tracking-wider uppercase transition-colors whitespace-nowrap cursor-pointer ${
                activeTab === tab 
                  ? 'text-[#063D2A]' 
                  : 'text-white hover:text-[#FCE138]'
              }`}
            >
              {tab}
            </button>
          ))}
        </div>
      </div>

      {/* MOBILE DROPDOWN */}
      <div className="md:hidden w-full px-6 mb-10 relative z-20">
        <div className="relative w-full">
          <button 
            onClick={() => setIsOpen(!isOpen)}
            className="w-full flex items-center justify-between px-6 py-3.5 bg-[#063D2A] text-[#FCE138] border border-[#042C1E] rounded-full text-xs font-black tracking-wider uppercase shadow-md"
          >
            <span>{activeTab}</span>
            <motion.div animate={{ rotate: isOpen ? 180 : 0 }}>
              <svg width="16" height="16" fill="none" stroke="currentColor" strokeWidth="2.5" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" d="M19 9l-7 7-7-7"></path></svg>
            </motion.div>
          </button>
          
          <AnimatePresence>
            {isOpen && (
              <motion.div 
                initial={{ opacity: 0, y: -10 }}
                animate={{ opacity: 1, y: 0 }}
                exit={{ opacity: 0, y: -10 }}
                className="absolute top-full left-0 right-0 mt-2 bg-[#063D2A] rounded-2xl shadow-2xl border border-[#042C1E] overflow-hidden flex flex-col z-30 p-1.5"
              >
                {tabs.map(tab => (
                  <button
                    key={tab}
                    onClick={() => { setActiveTab(tab); setIsOpen(false); }}
                    className={`px-5 py-3 text-left text-xs font-black tracking-wider uppercase rounded-xl transition-colors ${
                      tab === activeTab 
                        ? "bg-[#FCE138] text-[#063D2A]" 
                        : "text-white hover:text-[#FCE138] hover:bg-[#0F4432]"
                    }`}
                  >
                    {tab}
                  </button>
                ))}
              </motion.div>
            )}
          </AnimatePresence>
        </div>
      </div>
    </>
  )
}









